function phraseEntries() {
  return Object.entries(UI_PHRASES).map(([left, right]) => {
    const leftIsArabic = /[ء-ي]/.test(left);
    const arText = leftIsArabic ? left : right;
    const enText = leftIsArabic ? right : left;
    return current === 'ar' ? [enText, arText] : [arText, enText];
  });
}
function translateNode(node) {
  if (!node) return;
  const skip = (el) => el && /^(SCRIPT|STYLE|CODE|PRE)$/i.test(el.tagName);
  if (node.nodeType === 3) {
    const parent = node.parentElement;
    if (skip(parent) || /^(TEXTAREA|INPUT)$/i.test(parent?.tagName || '') || parent?.closest('[data-user-content],.user-content,.task-title,.ttl,.tnote,.transcript-content,.meeting-user-text,.project-list-name,.meeting-card h3,.meeting-card p,.project-summary-facts strong,.project-deliverable-row strong,.requirement-row p,.dashboard-project-heading,.finance-project-summary strong,.meeting-day-event b')) return;
    const original = node.nodeValue;
    const trimmed = original.trim();
    if (!trimmed) return;
    const leading = original.match(/^\s*/)?.[0] || '';
    const trailing = original.match(/\s*$/)?.[0] || '';
    let value = trimmed;
    for (const [from, to] of phraseEntries().sort((a,b) => b[0].length-a[0].length)) {
      if (from.length <= 3 ? value === from : value.includes(from)) value = from.length <= 3 ? to : value.split(from).join(to);
    }
    if (value !== trimmed) node.nodeValue = leading + value + trailing;
    return;
  }
  if (node.nodeType !== 1 && node !== document) return;
  const el = node.nodeType === 1 ? node : document.body;
  if (!el || skip(el)) return;
  for (const attr of ['placeholder','title','aria-label','alt']) {
    const old = el.getAttribute?.(attr);
    if (!old) continue;
    let next = old;
    for (const [from,to] of phraseEntries().sort((a,b)=>b[0].length-a[0].length)) if (next.includes(from)) next = next.split(from).join(to);
    if (next !== old) el.setAttribute(attr,next);
  }
  if (/^(TEXTAREA|INPUT)$/i.test(el.tagName || '')) return;
  for (const child of [...(el.childNodes || [])]) translateNode(child);
}
export function translateDom(root = document) { translateNode(root); }

function installDomTranslation() {
  if (typeof document === 'undefined') return;
  translateNode(document.body);
  if (domObserver || !document.body || typeof MutationObserver === 'undefined') return;
  domObserver = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') translateNode(record.target);
      else if (record.type === 'attributes') translateNode(record.target);
      else for (const added of record.addedNodes) translateNode(added);
    }
  });
  domObserver.observe(document.body,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['placeholder','title','aria-label','alt']});
}

